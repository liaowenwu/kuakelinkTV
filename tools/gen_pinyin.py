# -*- coding: utf-8 -*-
"""Generate Pinyin.java: hanzi -> pinyin-initials lookup for fuzzy search.

Run:  python tools/gen_pinyin.py
Needs: pip install pypinyin
Output: launcher/app/src/main/java/com/gathin/tvhome/Pinyin.java
"""
import sys

from pypinyin import pinyin as py_pinyin

OUT = "launcher/app/src/main/java/com/gathin/tvhome/Pinyin.java"


def initial_of(reading: str) -> str:
    r = reading.lower()
    for digraph, letter in (("zh", "z"), ("ch", "c"), ("sh", "s")):
        if r.startswith(digraph):
            return letter
    return r[0] if r else ""


def main() -> int:
    chars = []
    primary = []
    alternates = {}  # char -> extra initial letters (polyphones)
    for code in range(0x4E00, 0x9FFF):  # CJK Unified Ideographs
        ch = chr(code)
        try:
            readings = py_pinyin(ch, heteronym=True, errors=lambda x: [])
        except Exception:
            continue
        letters = []
        for group in readings:
            for reading in group:
                if not reading or not reading.isalpha():
                    continue
                ini = initial_of(reading)
                if ini and ini not in letters:
                    letters.append(ini)
        if not letters:
            continue
        chars.append(ch)
        primary.append(letters[0])
        if len(letters) > 1:
            alternates[ch] = "".join(letters[1:])

    alt = "".join(ch + alternates[ch] for ch in alternates)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("package com.gathin.tvhome;\n\n")
        f.write("/**\n")
        f.write(" * Generated by tools/gen_pinyin.py (pypinyin). Hanzi -> pinyin initials for FuzzySearch.\n")
        f.write(" * Do not edit by hand: re-run the generator instead.\n")
        f.write(" */\n")
        f.write("final class Pinyin {\n")
        f.write("    private static final String CHARS = \"")
        f.write("".join(chars))
        f.write("\";\n")
        f.write("    private static final String PRIMARY = \"")
        f.write("".join(primary))
        f.write("\";\n")
        f.write("    /** Polyphones whose readings start with different letters: char + extra letters. */\n")
        f.write("    private static final String ALT = \"")
        f.write(alt)
        f.write("\";\n\n")
        f.write("""    private static final java.util.Map<Character, String> ALT_MAP = new java.util.HashMap<>();

    static {
        for (int i = 0; i + 1 < ALT.length(); ) {
            char c = ALT.charAt(i);
            int j = i + 1;
            StringBuilder sb = new StringBuilder();
            while (j < ALT.length() && Character.isLetter(ALT.charAt(j))) sb.append(ALT.charAt(j++));
            ALT_MAP.put(c, sb.toString());
            i = j;
        }
    }

    private Pinyin() {}

    /** All possible initials for one hanzi (polyphones return several), e.g. '乐' -> "yl"; "" when unknown. */
    static String initials(char c) {
        int lo = 0, hi = CHARS.length() - 1;
        while (lo <= hi) {
            int mid = (lo + hi) >>> 1;
            char m = CHARS.charAt(mid);
            if (m < c) lo = mid + 1;
            else if (m > c) hi = mid - 1;
            else {
                String alt = ALT_MAP.get(c);
                return PRIMARY.charAt(mid) + (alt == null ? "" : alt);
            }
        }
        return "";
    }
}
""")
    print(f"wrote {OUT}: {len(chars)} hanzi, {len(alternates)} polyphones")
    return 0


if __name__ == "__main__":
    sys.exit(main())
